//! Generates the steward's policy dispatch from its transition tables (servers/steward.md,
//! "Machines": each machine has one table, and its dispatch and its state diagram are generated
//! from it, so neither can drift from the table).
//!
//! The tables are the single source of truth. This crate reads every `libs/steward/tables/*.md`
//! (skipping fenced code blocks and the generated diagrams), finds each table marked
//! `<!-- steward: NAME -->`, checks it, and emits:
//! - `libs/steward/src/gen/NAME.rs`: the machine's states and events, and its dispatch, an exhaustive `match`
//!   on (state, event) that calls the named guards and effects through the `Policy` table;
//! - `libs/steward/src/gen/mod.rs`: the modules, and `Policy` with one entry per guard and effect and
//!   `Policy::SHIPPED`;
//! - `libs/steward/tables/NAME.mermaid.md`: the state diagram the page includes;
//! - `libs/steward/elixir/gen/NAME.ex`: the Elixir reference's clause skeletons, the machine's rows as data,
//!   one clause per (state, event).
//!
//! The generated files are checked in; a test fails if they differ from what the tables produce
//! now, or if a file in those places is generated by no table any more. The notation is described
//! in `libs/steward/tables/README.md`.
//!
//! Host-only (`std`); nothing here runs on Redoubt.

