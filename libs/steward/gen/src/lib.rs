/// `EndLease` as an Elixir atom's name: `end_lease`.
fn snake(camel: &str) -> String {
    let mut s = String::new();
    for (i, c) in camel.chars().enumerate() {
        if c.is_ascii_uppercase() && i > 0 {
            s.push('_');
        }
        s.push(c.to_ascii_lowercase());
    }
    s
}

/// `approval_channel` as an Elixir module's name: `ApprovalChannel`.
fn camel(snake: &str) -> String { snake.split('_').map(|w| w[..1].to_ascii_uppercase() + &w[1..]).collect() }

fn elixir_atoms(names: &[&String]) -> String {
    let atoms: Vec<String> = names.iter().map(|n| format!(":{}", snake(n))).collect();
    format!("[{}]", atoms.join(", "))
}

/// One row as Elixir data: `{line, guards, effects, to}`.
fn elixir_row(r: &Row) -> String {
    let guards: Vec<String> = r
        .guards
        .iter()
        .map(|g| if g.negated { format!("{{:not, :{}}}", g.name) } else { format!(":{}", g.name) })
        .collect();
    let effects = match &r.effects {
        Effects::Unreachable => ":unreachable".to_string(),
        Effects::List(l) => format!("[{}]", l.iter().map(|e| format!(":{e}")).collect::<Vec<_>>().join(", ")),
    };
    let to = match &r.to {
        To::Nothing => ":nothing".to_string(),
        To::Same => ":stay".to_string(),
        To::State(s) => format!("{{:to, :{}}}", snake(s)),
    };
    format!("{{{}, [{}], {effects}, {to}}}", r.line, guards.join(", "))
}

/// The machine's clause skeletons for the Elixir reference: its final states as atoms, and one
/// clause of `rows/2` per (state, event), giving the rows to try in order, or `:no_row`.
pub fn elixir(m: &Machine) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "# The `{}` machine's final states and rows, for the Elixir reference.", m.name);
    let _ = writeln!(s, "#");
    let _ = writeln!(s, "# Generated by `redoubt-steward-gen` from `{}`.", m.source);
    let _ = writeln!(s, "# Do not edit: change the table and run `cargo run -p redoubt-steward-gen`.");
    let _ = writeln!(s, "defmodule Redoubt.Steward.Gen.{} do", camel(&m.name));
    let _ = writeln!(s, "  @moduledoc false\n");
    let finals: Vec<&String> = m.states.iter().filter(|st| m.is_final(st)).collect();
    let _ = writeln!(s, "  # A final state: no row leaves it, and the object is removed when it gets there.");
    let _ = writeln!(s, "  def finals, do: {}", elixir_atoms(&finals));
    let _ = writeln!(s);
    let _ = writeln!(s, "  # The rows for (from, event), in the order they are tried, each");
    let _ =
        writeln!(s, "  # {{line, guards, effects, to}}; `from` is nil before the object exists. A pair the");
    let _ = writeln!(s, "  # table gives no row is `:no_row`.");
    let froms: Vec<Option<&String>> = std::iter::once(None).chain(m.states.iter().map(Some)).collect();
    for from in froms {
        let pat = from.map_or("nil".into(), |st| format!(":{}", snake(st)));
        for e in &m.events {
            match m.group(from.map(String::as_str), e) {
                Some(g) => {
                    let _ = writeln!(s, "  def rows({pat}, :{}) do\n    [", snake(e));
                    for n in &g.rows {
                        let _ = writeln!(s, "      {},", elixir_row(&m.rows[*n]));
                    }
                    let _ = writeln!(s, "    ]\n  end");
                }
                None => {
                    let _ = writeln!(s, "  def rows({pat}, :{}), do: :no_row", snake(e));
                }
            }
        }
        let _ = writeln!(s);
    }
    s.truncate(s.trim_end().len());
    s.push_str("\nend\n");
    s
}

/// The machine's state diagram, which its page includes.
pub fn mermaid(m: &Machine) -> String {
    let mut s = String::new();
    let _ = writeln!(
        s,
        "<!-- Generated by redoubt-steward-gen from {}: do not edit. -->\n\n```mermaid\nstateDiagram-v2",
        m.source
    );
    for r in &m.rows {
        let To::State(to) = &r.to else { continue };
        let guards: Vec<String> =
            r.guards.iter().map(|g| format!("{}{}", if g.negated { "not " } else { "" }, g.name)).collect();
        let when = if guards.is_empty() { String::new() } else { format!(" [{}]", guards.join(", ")) };
        for from in &r.from {
            if from.as_ref() == Some(to) {
                continue;
            }
            let from = from.as_deref().unwrap_or("[*]");
            let _ = writeln!(s, "    {from} --> {to}: {}{when}", r.events.join(", "));
        }
    }
    for st in m.states.iter().filter(|st| m.is_final(st)) {
        let _ = writeln!(s, "    {st} --> [*]");
    }
    let _ = writeln!(s, "```\n*Figure: the `{}` machine, generated from its table.*", m.name);
    s
}

/// The files that may hold tables, relative to the repository root, sorted: the generated
/// diagrams are not among them.
pub fn sources(root: &Path) -> Result<Vec<PathBuf>, String> {
    let mut found = Vec::new();
    let entries = std::fs::read_dir(root.join(TABLES)).map_err(|e| format!("{TABLES}: {e}"))?;
    for entry in entries {
        let path = entry.map_err(|e| format!("{TABLES}: {e}"))?.path();
        let name = path.file_name().and_then(|n| n.to_str()).unwrap_or_default();
        if name.ends_with(".md") && !name.ends_with(DIAGRAM) {
            found.push(path.strip_prefix(root).map_err(|e| e.to_string())?.to_path_buf());
        }
    }
    found.sort();
    Ok(found)
}

/// Every machine in the tables.
pub fn machines(root: &Path) -> Result<Vec<Machine>, String> {
    let mut found = Vec::new();
    for src in sources(root)? {
        let text = std::fs::read_to_string(root.join(&src)).map_err(|e| format!("{}: {e}", src.display()))?;
        let name = src.to_str().ok_or("non-UTF-8 path")?.replace('\\', "/");
        found.push(parse(&name, &text)?);
    }
    link(found)
}

/// Every generated file (path relative to the repository root, contents), from the tables.
pub fn generate(root: &Path) -> Result<Vec<(PathBuf, String)>, String> {
    let machines = machines(root)?;
    let mut out = vec![(PathBuf::from(format!("{RUST_DIR}/mod.rs")), rust_mod(&machines))];
    for m in &machines {
        out.push((PathBuf::from(format!("{RUST_DIR}/{}.rs", m.name)), rust(m)));
        out.push((PathBuf::from(format!("{TABLES}/{}{DIAGRAM}", m.name)), mermaid(m)));
        out.push((PathBuf::from(format!("{ELIXIR_DIR}/{}.ex", m.name)), elixir(m)));
    }
    Ok(out)
}

/// Generated files that are missing or differ, and files in the output places that no table
/// produces any more.
pub fn stale(root: &Path) -> Result<Vec<PathBuf>, String> {
    let expected = generate(root)?;
    let mut stale = Vec::new();
    for (path, contents) in &expected {
        if std::fs::read_to_string(root.join(path)).ok().as_deref() != Some(contents.as_str()) {
            stale.push(path.clone());
        }
    }
    stale.extend(orphans(root, &expected));
    Ok(stale)
}

/// Files in the output places that no table generates: everything in the generated directory,
/// and the diagrams beside the tables.
pub fn orphans(root: &Path, expected: &[(PathBuf, String)]) -> Vec<PathBuf> {
    let mut found = Vec::new();
    for (dir, all) in [(RUST_DIR, true), (ELIXIR_DIR, true), (TABLES, false)] {
        let Ok(entries) = std::fs::read_dir(root.join(dir)) else { continue };
        for entry in entries.flatten() {
            let name = entry.file_name();
            if !all && !name.to_str().is_some_and(|n| n.ends_with(DIAGRAM)) {
                continue;
            }
            let rel = Path::new(dir).join(name);
            if !expected.iter().any(|(p, _)| *p == rel) {
                found.push(rel);
            }
        }
    }
    found.sort();
    found
}

