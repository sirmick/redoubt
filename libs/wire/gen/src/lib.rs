//! Generates the typed-message codecs from the tables in the design notes (WIRE.md: "one
//! layout per message type, defined by a table in the owning server's note ... the Rust and
//! Elixir codecs are generated from those tables, so sender and receiver cannot disagree").
//!
//! The notes are the single source of truth. This crate reads every `docs/*.md`
//! and `libs/wire/tables/*.md` (skipping fenced code blocks), finds each message table
//! marked `<!-- wire: NAME -->` and each error table marked `<!-- wire-errors: NAME -->`, and
//! emits `libs/wire/src/proto/NAME.rs`, `libs/wire/elixir/proto/NAME.ex`, and
//! `libs/wire/src/proto/mod.rs` listing the Rust modules. The generated files are checked
//! in; a test fails if they differ from what the notes produce now, or if a file in those
//! directories is generated by no table any more (an orphan: `cargo run -p redoubt-wire-gen`
//! names it, and a person deletes it). The table format is described in
//! `libs/wire/tables/example.md`.
//!
//! Host-only (`std`); nothing here runs on Redoubt.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use redoubt_wire::typed::{HandleKind, INLINE_BYTES, MALFORMED, MAX_MSG_HANDLES};

const MESSAGE_HEADER: [&str; 4] = ["Opcode", "Message", "Fields", "Reply"];
const ERROR_HEADER: [&str; 2] = ["Code", "Error"];
const MESSAGE_MARKER: &str = "<!-- wire:";
const ERROR_MARKER: &str = "<!-- wire-errors:";
/// The opcode floor on a 9P endpoint: `ninep_common` reserves 1-15 there, so a protocol served
/// on a 9P endpoint (a table marked `<!-- wire: NAME ninep -->`) starts at 16 (WIRE.md, Messages).
const NINEP_FIRST_OPCODE: u32 = 16;
/// The marker suffix that says a protocol is served on a 9P endpoint.
const NINEP_SUFFIX: &str = " ninep";

/// A field's type, as written in a table.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Ty {
    U8,
    U16,
    U32,
    U64,
    Str,
    Bytes,
    /// The handle in this slot, and the kind of object it must name (documentation: kinds
    /// are checked by use, WIRE.md); carries no bytes.
    Handle(usize, HandleKind),
}

impl Ty {
    /// (encoded size if fixed, `Reader`/`Writer` method and Elixir type, Rust type). Strings
    /// and byte arrays have no fixed size; a handle has size 0 (it travels in a slot).
    fn info(self) -> (Option<usize>, &'static str, &'static str) {
        match self {
            Ty::U8 => (Some(1), "u8", "u8"),
            Ty::U16 => (Some(2), "u16", "u16"),
            Ty::U32 => (Some(4), "u32", "u32"),
            Ty::U64 => (Some(8), "u64", "u64"),
            Ty::Str => (None, "string", "&'a str"),
            Ty::Bytes => (None, "bytes", "&'a [u8]"),
            Ty::Handle(..) => (Some(0), "handle", ""),
        }
    }

    fn bits(self) -> usize {
        self.info().0.unwrap_or(0) * 8
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Field {
    pub name: String,
    pub ty: Ty,
}

/// The fields that are encoded (everything but handles).
fn data(fields: &[Field]) -> impl Iterator<Item = &Field> {
    fields.iter().filter(|f| !matches!(f.ty, Ty::Handle(..)))
}

/// The handle fields, with their slot and kind.
fn handles(fields: &[Field]) -> impl Iterator<Item = (&Field, usize, HandleKind)> {
    fields.iter().filter_map(|f| match f.ty {
        Ty::Handle(slot, kind) => Some((f, slot, kind)),
        _ => None,
    })
}

/// `` `name` (slot N, KIND) `` for each handle, for the generated docs; `None` if there are none.
fn handle_doc(fields: &[Field]) -> Option<String> {
    let hs: Vec<String> =
        handles(fields).map(|(f, slot, kind)| format!("`{}` (slot {slot}, {})", f.name, kind.name())).collect();
    (!hs.is_empty()).then(|| hs.join(", "))
}

/// Every field has a fixed size and together they fit in words 1..=3.
fn fits_inline(fields: &[Field]) -> bool {
    let sizes: Option<Vec<usize>> = fields.iter().map(|f| f.ty.info().0).collect();
    sizes.is_some_and(|s| s.iter().sum::<usize>() <= INLINE_BYTES)
}

fn borrows(fields: &[Field]) -> bool {
    data(fields).any(|f| matches!(f.ty, Ty::Str | Ty::Bytes))
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MessageDef {
    pub opcode: u32,
    pub name: String,
    /// In table order, handles included.
    pub fields: Vec<Field>,
    /// The reply's fields; empty for a reply that is its status alone.
    pub reply: Vec<Field>,
}

impl MessageDef {
    /// Inline if the request's fields and the reply's fields each fit in the words; a
    /// message whose reply needs a buffer is buffer-shaped, because reply data can only
    /// come back in the caller's lend (WIRE.md).
    pub fn inline(&self) -> bool {
        fits_inline(&self.fields) && fits_inline(&self.reply)
    }

    fn type_name(&self) -> String {
        camel(&self.name)
    }

    fn reply_type(&self) -> String {
        format!("{}Reply", camel(&self.name))
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ErrorDef {
    pub code: u32,
    pub name: String,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Protocol {
    pub name: String,
    /// The note the table came from, relative to the repository root.
    pub source: String,
    pub messages: Vec<MessageDef>,
    /// From the protocol's error table (every protocol has one).
    pub errors: Vec<ErrorDef>,
}

/// An error table, before it is joined with its protocol.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ErrorTable {
    pub protocol: String,
    pub source: String,
    pub errors: Vec<ErrorDef>,
}

/// Rust keywords (struct fields and modules) and Elixir reserved words (map keys, atoms) a
/// name may not be. Generated code never binds a bare field name, so no local can clash.
const RESERVED: &[&str] = &[
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for", "if",
    "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "self", "static",
    "struct", "super", "trait", "true", "type", "unsafe", "use", "where", "while", "async", "await", "dyn",
    "abstract", "become", "box", "do", "final", "macro", "override", "priv", "typeof", "unsized", "virtual",
    "yield", "try", "gen", "and", "or", "not", "when", "end", "nil", "catch", "rescue", "after",
];

/// Type names a message may not produce: the generated module's own items and imports, and
/// the Rust prelude's names, which the generated code uses (`Result`, `Ok`, ...).
const RESERVED_TYPES: &[&str] = &[
    "Message", "Reply", "ErrorCode", "Error", "Reader", "Writer", "Layout", "Words", "Result", "Ok",
    "Err", "Option", "Some", "None", "Box", "Vec", "String", "Copy", "Clone", "Debug", "PartialEq", "Eq",
    "PartialOrd", "Ord", "Hash", "Default", "Drop", "Send", "Sync", "Sized", "Unpin", "Fn", "FnMut", "FnOnce",
    "From", "Into", "TryFrom", "TryInto", "AsRef", "AsMut", "Iterator", "IntoIterator", "DoubleEndedIterator",
    "ExactSizeIterator", "Extend", "FromIterator", "ToOwned", "ToString",
];

fn check_ident(what: &str, name: &str) -> Result<(), String> {
    let mut chars = name.chars();
    let ok = chars.next().is_some_and(|c| c.is_ascii_lowercase())
        && chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
        && !name.ends_with('_')
        && !name.contains("__");
    if !ok {
        return Err(format!("{what} `{name}` must be snake_case ([a-z][a-z0-9_]*)"));
    }
    if RESERVED.contains(&name) {
        return Err(format!("{what} `{name}` is reserved in generated code"));
    }
    Ok(())
}

fn camel(name: &str) -> String {
    name.split('_')
        .map(|part| {
            let mut c = part.chars();
            c.next().map(|first| first.to_ascii_uppercase().to_string() + c.as_str()).unwrap_or_default()
        })
        .collect()
}

fn cells(line: &str) -> Option<Vec<&str>> {
    let inner = line.trim().strip_prefix('|')?.strip_suffix('|')?;
    Some(inner.split('|').map(str::trim).collect())
}

fn backticked(s: &str) -> Option<&str> {
    s.strip_prefix('`')?.strip_suffix('`')
}

/// A nonzero decimal `u32` with one spelling: no sign, no leading zeros. Code 0 is the
/// reply status "ok", so neither an opcode nor an error code may be 0.
fn parse_code(what: &str, s: &str) -> Result<u32, String> {
    let canonical = !s.is_empty() && (s == "0" || !s.starts_with('0')) && s.bytes().all(|b| b.is_ascii_digit());
    let value: u32 = s
        .parse()
        .ok()
        .filter(|_| canonical)
        .ok_or_else(|| format!("{what} `{s}` is not a decimal u32 without leading zeros"))?;
    if value == 0 {
        return Err(format!("{what} 0 is reserved (a reply status of 0 means success)"));
    }
    Ok(value)
}

fn parse_type(s: &str, handles_so_far: usize) -> Result<Ty, String> {
    Ok(match s {
        "u8" => Ty::U8,
        "u16" => Ty::U16,
        "u32" => Ty::U32,
        "u64" => Ty::U64,
        "string" => Ty::Str,
        "bytes" => Ty::Bytes,
        _ => {
            // `handle[N] KIND`: the slot, one ASCII space, then the kind of object the handle
            // must name. One spelling: no tabs, doubled or non-ASCII spaces.
            let (slot, kind) = match s.split_once(' ') {
                Some((slot, kind)) => (slot, Some(kind)),
                None => (s, None),
            };
            let slot = slot
                .strip_prefix("handle[")
                .and_then(|r| r.strip_suffix(']'))
                .filter(|n| n.bytes().all(|b| b.is_ascii_digit()) && (*n == "0" || !n.starts_with('0')))
                .and_then(|n| n.parse::<usize>().ok())
                .ok_or_else(|| format!("unknown type `{s}`"))?;
            let kinds = || HandleKind::ALL.map(HandleKind::name).join(", ");
            let kind = match kind {
                None => {
                    return Err(format!("`{s}`: a handle needs its kind, `handle[{slot}] KIND` (one of {})", kinds()));
                }
                Some(k) if k.chars().any(char::is_whitespace) || k.is_empty() => {
                    return Err(format!("`{s}`: expected `handle[{slot}] KIND`, with one space"));
                }
                Some(k) => HandleKind::from_name(k)
                    .ok_or_else(|| format!("`{s}`: unknown handle kind `{k}` (one of {})", kinds()))?,
            };
            if slot != handles_so_far {
                return Err(format!("`{s}`: handle slots must be numbered 0, 1, ... in order"));
            }
            if slot >= MAX_MSG_HANDLES {
                return Err(format!("`{s}`: a message carries at most {MAX_MSG_HANDLES} handles"));
            }
            Ty::Handle(slot, kind)
        }
    })
}

/// A comma-separated list of `` `name: type` ``, or `-` for none.
fn parse_fields(cell: &str) -> Result<Vec<Field>, String> {
    let mut parsed: Vec<Field> = Vec::new();
    if cell == "-" {
        return Ok(parsed);
    }
    for item in cell.split(',') {
        let item = item.trim_ascii();
        let inner = backticked(item).ok_or_else(|| format!("field `{item}` must be `name: type` in backticks"))?;
        let (fname, ty) = inner.split_once(':').ok_or_else(|| format!("field `{inner}` has no `: type`"))?;
        let fname = fname.trim_ascii();
        check_ident("field", fname)?;
        if parsed.iter().any(|f| f.name == fname) {
            return Err(format!("field `{fname}` appears twice"));
        }
        let slots = handles(&parsed).count();
        parsed.push(Field { name: fname.to_string(), ty: parse_type(ty.trim_ascii(), slots)? });
    }
    Ok(parsed)
}

fn parse_message(row: &[&str]) -> Result<MessageDef, String> {
    let [opcode, name, fields, reply] = row else {
        return Err(format!("a row has {} cells, expected 4", row.len()));
    };
    let opcode = parse_code("opcode", opcode)?;
    let name = backticked(name).ok_or_else(|| format!("message name `{name}` must be in backticks"))?;
    check_ident("message", name)?;
    Ok(MessageDef { opcode, name: name.to_string(), fields: parse_fields(fields)?, reply: parse_fields(reply)? })
}

/// The name of error code 1, every protocol's (WIRE.md, Errors).
const MALFORMED_NAME: &str = "malformed";

/// The error every protocol has: code 1.
fn malformed() -> ErrorDef {
    ErrorDef { code: MALFORMED, name: MALFORMED_NAME.into() }
}

fn parse_error(row: &[&str]) -> Result<ErrorDef, String> {
    let [code, name] = row else {
        return Err(format!("a row has {} cells, expected 2", row.len()));
    };
    let code = parse_code("error code", code)?;
    let name = backticked(name).ok_or_else(|| format!("error name `{name}` must be in backticks"))?;
    check_ident("error", name)?;
    Ok(ErrorDef { code, name: name.to_string() })
}

/// The tables found in one note.
#[derive(Debug, Default, PartialEq, Eq)]
pub struct Tables {
    pub protocols: Vec<Protocol>,
    pub errors: Vec<ErrorTable>,
}

/// Finds and parses every wire table in one markdown file. Fenced code blocks are skipped,
/// so a note can show a table without defining one.
pub fn parse(source: &str, text: &str) -> Result<Tables, String> {
    let lines: Vec<&str> = text.lines().collect();
    let line = |i: usize| lines.get(i).map(|l| l.trim());
    let at = |n: usize, msg: String| format!("{source}:{}: {msg}", n + 1);
    let mut tables = Tables::default();
    let mut in_fence = false;
    let mut i = 0;
    while let Some(trimmed) = line(i) {
        if trimmed.starts_with("```") || trimmed.starts_with("~~~") {
            in_fence = !in_fence;
        }
        if in_fence {
            i += 1;
            continue;
        }
        // A table with our header but no marker would be silently ignored: refuse it.
        if cells(trimmed).is_some_and(|c| c == MESSAGE_HEADER || c == ERROR_HEADER) {
            return Err(at(i, "a wire table needs a `<!-- wire: NAME -->` or `<!-- wire-errors: NAME -->` line before it".into()));
        }
        let (rest, header) = if let Some(rest) = trimmed.strip_prefix(ERROR_MARKER) {
            (rest, &ERROR_HEADER[..])
        } else if let Some(rest) = trimmed.strip_prefix(MESSAGE_MARKER) {
            (rest, &MESSAGE_HEADER[..])
        } else {
            i += 1;
            continue;
        };
        let rest = rest.strip_suffix("-->");
        let (name, ninep) = match (rest, header == MESSAGE_HEADER) {
            // A protocol served on a 9P endpoint is marked `<!-- wire: NAME ninep -->` (WIRE.md).
            (Some(rest), true) => match rest.trim().strip_suffix(NINEP_SUFFIX) {
                Some(name) => (name.trim(), true),
                None => (rest.trim(), false),
            },
            (Some(rest), false) => (rest.trim(), false),
            (None, _) => return Err(at(i, "malformed wire marker".into())),
        };
        check_ident("protocol", name).map_err(|e| at(i, e))?;
        let marker = i;
        i += 1;
        while line(i).is_some_and(str::is_empty) {
            i += 1;
        }
        if line(i).and_then(cells).is_none_or(|c| c != header) {
            return Err(at(i, format!("expected the header `| {} |`", header.join(" | "))));
        }
        i += 1;
        let separator = line(i).and_then(cells);
        if separator.is_none_or(|c| c.len() != header.len() || c.iter().any(|s| s.len() < 3 || !s.chars().all(|ch| ch == '-'))) {
            return Err(at(i, "expected a separator row of `---` cells".into()));
        }
        i += 1;
        // Every line up to a blank line or the end of the file is a row; nothing is skipped.
        let mut rows = Vec::new();
        while let Some(text) = line(i).filter(|l| !l.is_empty()) {
            let row = cells(text).ok_or_else(|| {
                at(i, format!("table `{name}` must end at a blank line (a row starts and ends with `|`)"))
            })?;
            rows.push((i, row));
            i += 1;
        }
        // An error table may be empty: `malformed` is every protocol's, and a protocol may
        // have no errors of its own.
        if rows.is_empty() && header == MESSAGE_HEADER {
            return Err(at(marker, format!("table `{name}` has no rows")));
        }
        // A row cut off from its table by a blank line would otherwise be read as prose.
        let mut next = i;
        while line(next).is_some_and(str::is_empty) {
            next += 1;
        }
        if line(next).is_some_and(|l| l.starts_with('|') || (l.contains('|') && l.contains('`'))) {
            return Err(at(next, format!("this looks like a row of `{name}`, but its table ended at the blank line above")));
        }
        if header == ERROR_HEADER {
            // Code 1 is `malformed` in every protocol (WIRE.md, Errors): added here, and a
            // table may not give the code (or the name) a meaning of its own.
            let mut errors: Vec<ErrorDef> = vec![malformed()];
            for (n, row) in rows {
                let e = parse_error(&row).map_err(|e| at(n, e))?;
                if e.code == MALFORMED || e.name == MALFORMED_NAME {
                    return Err(at(n, format!(
                        "error `{}` (code {}): code {MALFORMED} is `malformed` in every protocol, added by the generator; \
                         a protocol's own codes start at 2",
                        e.name, e.code
                    )));
                }
                if errors.iter().any(|o| o.code == e.code || camel(&o.name) == camel(&e.name)) {
                    return Err(at(n, format!("error `{}` or code {} used twice", e.name, e.code)));
                }
                errors.push(e);
            }
            tables.errors.push(ErrorTable { protocol: name.to_string(), source: source.to_string(), errors });
        } else {
            let mut messages: Vec<MessageDef> = Vec::new();
            let mut types: Vec<String> = Vec::new();
            for (n, row) in rows {
                let m = parse_message(&row).map_err(|e| at(n, e))?;
                if messages.iter().any(|o| o.opcode == m.opcode) {
                    return Err(at(n, format!("opcode {} used twice", m.opcode)));
                }
                // `ninep_common` reserves opcodes 1-15 on a 9P endpoint, so a protocol served
                // there starts at 16; an unmarked table starts at 1 (WIRE.md, Messages).
                if ninep && m.opcode < NINEP_FIRST_OPCODE {
                    return Err(at(n, format!(
                        "message `{}`: opcode {} is below {NINEP_FIRST_OPCODE}, reserved for `ninep_common`, \
                         because `{name}` is served on a 9P endpoint (WIRE.md)",
                        m.name, m.opcode
                    )));
                }
                // Every Rust type the message produces must be new: `a_reply` and the
                // reply of `a` would both be `AReply`.
                let new_types = vec![m.type_name(), m.reply_type()];
                for t in &new_types {
                    if RESERVED_TYPES.contains(&t.as_str()) {
                        return Err(at(n, format!("message `{}` would make the Rust type `{t}`, which the generated code already uses", m.name)));
                    }
                    if types.contains(t) || messages.iter().any(|o| o.name == m.name) {
                        return Err(at(n, format!("message `{}` defined twice (as the Rust type `{t}`)", m.name)));
                    }
                }
                types.extend(new_types);
                messages.push(m);
            }
            let protocol =
                Protocol { name: name.to_string(), source: source.to_string(), messages, errors: Vec::new() };
            tables.protocols.push(protocol);
        }
    }
    if in_fence {
        return Err(at(lines.len(), "unclosed code fence".into()));
    }
    Ok(tables)
}

/// Joins every protocol with its error table, sorted by name. Every protocol has exactly
/// one error table (WIRE.md).
pub fn link(tables: Vec<Tables>) -> Result<Vec<Protocol>, String> {
    let mut protocols: Vec<Protocol> = Vec::new();
    let mut errors: Vec<ErrorTable> = Vec::new();
    for t in tables {
        for p in t.protocols {
            if let Some(other) = protocols.iter().find(|o| o.name == p.name) {
                return Err(format!("protocol `{}` is defined in both {} and {}", p.name, other.source, p.source));
            }
            protocols.push(p);
        }
        errors.extend(t.errors);
    }
    for e in errors {
        let p = protocols
            .iter_mut()
            .find(|p| p.name == e.protocol)
            .ok_or_else(|| format!("{}: error table for unknown protocol `{}`", e.source, e.protocol))?;
        if !p.errors.is_empty() {
            return Err(format!("{}: protocol `{}` has two error tables", e.source, e.protocol));
        }
        p.errors = e.errors;
    }
    if let Some(p) = protocols.iter().find(|p| p.errors.is_empty()) {
        return Err(format!("{}: protocol `{}` has no `<!-- wire-errors: {} -->` table", p.source, p.name, p.name));
    }
    protocols.sort_by(|a, b| a.name.cmp(&b.name));
    Ok(protocols)
}

/// One Rust struct per request or reply.
fn rust_struct(s: &mut String, doc: &str, name: &str, fields: &[Field]) {
    let _ = writeln!(s, "\n{doc}");
    if let Some(hs) = handle_doc(fields) {
        let _ = writeln!(s, "///\n/// Handle slots: {hs}.");
        s.push_str("/// Kinds are documentation, checked by use: a handle of the wrong kind gets `WrongObject`\n");
        s.push_str("/// on first use.\n");
    }
    let _ = writeln!(s, "#[derive(Debug, Clone, Copy, PartialEq, Eq)]");
    if data(fields).next().is_none() {
        let _ = writeln!(s, "pub struct {name} {{}}");
        return;
    }
    let lt = if borrows(fields) { "<'a>" } else { "" };
    let _ = writeln!(s, "pub struct {name}{lt} {{");
    for f in data(fields) {
        let _ = writeln!(s, "    pub {}: {},", f.name, f.ty.info().2);
    }
    s.push_str("}\n");
}

/// One variant of a generated `Message` or `Reply` enum.
struct Row<'p> {
    opcode: u32,
    /// The message's name in CamelCase, for both enums.
    variant: String,
    /// `Name` or `NameReply`.
    ty: String,
    fields: &'p [Field],
    inline: bool,
}

/// A `Message` or `Reply` enum with its codec, `rows` in table order.
fn rust_enum(s: &mut String, kind: &str, doc: &str, rows: &[Row<'_>]) {
    let lt = if rows.iter().any(|r| borrows(r.fields)) { "<'a>" } else { "" };
    let _ = writeln!(s, "\n/// {doc}");
    let _ = writeln!(s, "#[derive(Debug, Clone, Copy, PartialEq, Eq)]");
    let _ = writeln!(s, "pub enum {kind}{lt} {{");
    for r in rows {
        let flt = if borrows(r.fields) { "<'a>" } else { "" };
        let _ = writeln!(s, "    {}({}{flt}),", r.variant, r.ty);
    }
    s.push_str("}\n");

    let _ = writeln!(s, "\nimpl<'a> {kind}{lt} {{");
    s.push_str("    /// The handles it carries, by slot.\n");
    s.push_str("    pub fn handle_names(&self) -> &'static [&'static str] {\n        match self {\n");
    for r in rows {
        let names: Vec<String> = handles(r.fields).map(|(f, ..)| format!("{:?}", f.name)).collect();
        let _ = writeln!(s, "            {kind}::{}(_) => &[{}],", r.variant, names.join(", "));
    }
    s.push_str("        }\n    }\n\n");
    let key = if kind == "Reply" { "The opcode of the request this replies to." } else { "The opcode in word 0." };
    let _ = writeln!(s, "    /// {key}");
    s.push_str("    fn opcode(&self) -> u32 {\n        match self {\n");
    for r in rows {
        let _ = writeln!(s, "            {kind}::{}(_) => {},", r.variant, r.opcode);
    }
    s.push_str("        }\n    }\n\n");

    // write
    let any_data = rows.iter().any(|r| data(r.fields).next().is_some());
    let w = if any_data { "w" } else { "_w" };
    let _ = writeln!(s, "    fn write(&self, {w}: &mut Writer<'_>) -> Result<(), Error> {{");
    s.push_str("        match self {\n");
    for r in rows {
        let d: Vec<&Field> = data(r.fields).collect();
        match d.as_slice() {
            [] => {
                let _ = writeln!(s, "            {kind}::{}(_) => Ok(()),", r.variant);
            }
            [f] => {
                let _ = writeln!(s, "            {kind}::{}(m) => w.{}(m.{}),", r.variant, f.ty.info().1, f.name);
            }
            _ => {
                let _ = writeln!(s, "            {kind}::{}(m) => {{", r.variant);
                for (i, f) in d.iter().enumerate() {
                    let q = if i + 1 == d.len() { "" } else { "?;" };
                    let _ = writeln!(s, "                w.{}(m.{}){q}", f.ty.info().1, f.name);
                }
                s.push_str("            }\n");
            }
        }
    }
    s.push_str("        }\n    }\n\n");

    // read_inline (inline rows only; the reader holds a copy of the words) and read_buffer.
    for (fname, rlt, only_inline) in [("read_inline", "'_", true), ("read_buffer", "'a", false)] {
        let chosen: Vec<&Row<'_>> = rows.iter().filter(|r| r.inline || !only_inline).collect();
        let reads = chosen.iter().any(|r| data(r.fields).next().is_some());
        let r = if reads { "r" } else { "_r" };
        if chosen.is_empty() {
            // A protocol with no inline messages (only a `_` arm would be unreachable code).
            let _ = writeln!(s, "    fn {fname}(_opcode: u32, {r}: &mut Reader<{rlt}>) -> Result<Self, Error> {{");
            s.push_str("        Err(Error::BadOpcode)\n    }\n\n");
            continue;
        }
        let _ = writeln!(s, "    fn {fname}(opcode: u32, {r}: &mut Reader<{rlt}>) -> Result<Self, Error> {{");
        s.push_str("        Ok(match opcode {\n");
        for r in chosen {
            let inits: Vec<String> = data(r.fields).map(|f| format!("{}: r.{}()?", f.name, f.ty.info().1)).collect();
            let body = if inits.is_empty() { "{}".to_string() } else { format!("{{ {} }}", inits.join(", ")) };
            let _ = writeln!(s, "            {} => {kind}::{}({} {body}),", r.opcode, r.variant, r.ty);
        }
        s.push_str("            _ => return Err(Error::BadOpcode),\n        })\n    }\n\n");
    }
}

/// The generated Rust module for one protocol.
pub fn rust(p: &Protocol) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "//! Typed messages of the `{}` protocol.", p.name);
    let _ = writeln!(s, "//!");
    let _ = writeln!(s, "//! Generated by `redoubt-wire-gen` from the tables in `{}`.", p.source);
    let _ = writeln!(s, "//! Do not edit: change the tables and run `cargo run -p redoubt-wire-gen`.");
    s.push('\n');
    s.push_str("use crate::codec::{Error, Reader, Writer};\nuse crate::typed::{self, Layout, Words};\n");
    for m in &p.messages {
        let shape = if m.inline() { "inline" } else { "buffer" };
        let doc = format!("/// `{}`: opcode {}, {shape}; reply [`{}`].", m.name, m.opcode, m.reply_type());
        rust_struct(&mut s, &doc, &m.type_name(), &m.fields);
        rust_struct(&mut s, &format!("/// The reply to [`{}`].", m.type_name()), &m.reply_type(), &m.reply);
    }

    let layouts = |rows: Vec<(u32, bool, usize)>| {
        rows.iter()
            .map(|(op, inline, h)| format!("    Layout {{ opcode: {op}, inline: {inline}, handles: {h} }},\n"))
            .collect::<String>()
    };
    let requests = layouts(p.messages.iter().map(|m| (m.opcode, m.inline(), handles(&m.fields).count())).collect());
    let _ = write!(s, "\n/// Requests by opcode.\nconst REQUESTS: &[Layout] = &[\n{requests}];\n");
    let rows: Vec<Row<'_>> = p
        .messages
        .iter()
        .map(|m| Row { opcode: m.opcode, variant: m.type_name(), ty: m.type_name(), fields: &m.fields, inline: m.inline() })
        .collect();
    rust_enum(&mut s, "Message", "Every request of the protocol.", &rows);
    s.push_str("    /// Decodes a received request: its words, the buffer that came with it (empty if\n");
    s.push_str("    /// none), and how many handles it carried.\n");
    s.push_str("    pub fn decode(words: &Words, buf: &'a [u8], handles: usize) -> Result<Self, Error> {\n");
    s.push_str("        let layout = typed::layout(REQUESTS, typed::opcode(words)?)?;\n");
    s.push_str("        typed::decode(layout, words, buf, handles, Self::read_inline, Self::read_buffer)\n    }\n\n");
    s.push_str("    /// Encodes the request: returns its words, and writes the fields into `buf` if it is\n");
    s.push_str("    /// a buffer message (the buffer's length is then in word 1).\n");
    s.push_str("    pub fn encode(&self, buf: &mut [u8]) -> Result<Words, Error> {\n");
    s.push_str("        let opcode = self.opcode();\n");
    s.push_str("        typed::encode(typed::layout(REQUESTS, opcode)?, opcode, buf, |w| self.write(w))\n    }\n\n");
    s.push_str("    /// Decodes a request written into a 9P file: all of `bytes` is one operation.\n");
    s.push_str("    pub fn decode_file(bytes: &'a [u8]) -> Result<Self, Error> {\n");
    s.push_str("        typed::decode_file(REQUESTS, bytes, Self::read_buffer)\n    }\n\n");
    s.push_str("    /// Writes the request in the file framing into the front of `out`; returns its length.\n");
    s.push_str("    pub fn encode_file(&self, out: &mut [u8]) -> Result<usize, Error> {\n");
    s.push_str("        typed::encode_file(typed::layout(REQUESTS, self.opcode())?, out, |w| self.write(w))\n    }\n}\n");

    let replies = layouts(p.messages.iter().map(|m| (m.opcode, m.inline(), handles(&m.reply).count())).collect());
    let _ = write!(s, "\n/// Replies, by the opcode of their request.\nconst REPLIES: &[Layout] = &[\n{replies}];\n");
    let rows: Vec<Row<'_>> = p
        .messages
        .iter()
        .map(|m| Row { opcode: m.opcode, variant: m.type_name(), ty: m.reply_type(), fields: &m.reply, inline: m.inline() })
        .collect();
    rust_enum(&mut s, "Reply", "Every successful reply of the protocol, named after its request.", &rows);
    s.push_str("    /// Decodes the reply to the request with `opcode` (the caller knows what it sent):\n");
    s.push_str("    /// `Ok(Ok(reply))`, `Ok(Err(code))`\n");
    s.push_str("    /// for an error reply, or `Err` if the reply is malformed.\n");
    s.push_str("    pub fn decode(opcode: u32, words: &Words, buf: &'a [u8], handles: usize) -> Result<Result<Self, ErrorCode>, Error> {\n");
    s.push_str("        let layout = typed::layout(REPLIES, opcode)?;\n");
    s.push_str("        if let Some(code) = typed::reply_status(words, handles)? {\n");
    s.push_str("            return ErrorCode::from_code(code).map(Err).ok_or(Error::BadStatus);\n        }\n");
    s.push_str("        typed::decode(layout, words, buf, handles, Self::read_inline, Self::read_buffer).map(Ok)\n    }\n\n");
    s.push_str("    /// Encodes the reply (status 0): returns its words, and writes the fields into `buf`\n");
    s.push_str("    /// (the caller's lend) if it is a buffer message.\n");
    s.push_str("    pub fn encode(&self, buf: &mut [u8]) -> Result<Words, Error> {\n");
    s.push_str("        typed::encode(typed::layout(REPLIES, self.opcode())?, 0, buf, |w| self.write(w))\n    }\n}\n");

    s.push_str("\n/// The protocol's error codes: word 0 of an error reply. Code 1, `Malformed`, is every\n");
    s.push_str("/// protocol's: a request that does not decode (WIRE.md, Errors).\n");
    s.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq)]\npub enum ErrorCode {\n");
    for e in &p.errors {
        let _ = writeln!(s, "    {},", camel(&e.name));
    }
    s.push_str("}\n\nimpl ErrorCode {\n    pub fn code(self) -> u32 {\n        match self {\n");
    for e in &p.errors {
        let _ = writeln!(s, "            ErrorCode::{} => {},", camel(&e.name), e.code);
    }
    s.push_str("        }\n    }\n\n    pub fn from_code(code: u32) -> Option<Self> {\n        match code {\n");
    for e in &p.errors {
        let _ = writeln!(s, "            {} => Some(ErrorCode::{}),", e.code, camel(&e.name));
    }
    s.push_str("            _ => None,\n        }\n    }\n\n");
    s.push_str("    /// The words of the error reply (no buffer, no handles).\n");
    s.push_str("    pub fn encode(self) -> Words {\n        typed::error_reply(self.code())\n    }\n}\n");
    s
}

