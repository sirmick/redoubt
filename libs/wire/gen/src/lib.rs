fn elixir_fields(fields: &[Field]) -> String {
    let f: Vec<String> = data(fields).map(|f| format!("{{:{}, :{}}}", f.name, f.ty.info().1)).collect();
    let h: Vec<String> = handles(fields).map(|(f, ..)| format!(":{}", f.name)).collect();
    format!("[{}], [{}]", f.join(", "), h.join(", "))
}

/// `enc` and `read` clauses for one request or reply.
fn elixir_clauses(enc: &mut String, read: &mut String, dir: &str, m: &MessageDef, fields: &[Field]) {
    let d: Vec<&Field> = data(fields).collect();
    let pat: Vec<String> = d.iter().map(|f| format!("{}: v_{}", f.name, f.name)).collect();
    let parts: Vec<String> = d
        .iter()
        .map(|f| match f.ty {
            Ty::Str => format!("W.str(v_{})", f.name),
            Ty::Bytes => format!("W.bytes(v_{})", f.name),
            ty => format!("W.u(v_{}, {})", f.name, ty.bits()),
        })
        .collect();
    let _ = writeln!(
        enc,
        "  defp enc(:{dir}, :{}, %{{{}}} = f) when map_size(f) == {}, do: {{{}, [{}]}}",
        m.name,
        pat.join(", "),
        d.len(),
        m.opcode,
        parts.join(", ")
    );
    let mut segs: Vec<String> = Vec::new();
    for f in &d {
        match f.ty {
            Ty::Str | Ty::Bytes => {
                let len_bits = if f.ty == Ty::Str { 16 } else { 32 };
                segs.push(format!("n_{}::little-{len_bits}", f.name));
                segs.push(format!("v_{}::binary-size(n_{})", f.name, f.name));
            }
            ty => segs.push(format!("v_{}::little-{}", f.name, ty.bits())),
        }
    }
    segs.push("rest::binary".into());
    let map: Vec<String> = d.iter().map(|f| format!("{}: v_{}", f.name, f.name)).collect();
    let result = format!("{{:ok, :{}, %{{{}}}, rest}}", m.name, map.join(", "));
    let strings: Vec<String> = d.iter().filter(|f| f.ty == Ty::Str).map(|f| format!("v_{}", f.name)).collect();
    let result = if strings.is_empty() { result } else { format!("W.utf8([{}], {result})", strings.join(", ")) };
    let _ = writeln!(read, "  defp read(:{dir}, {}, <<{}>>), do: {result}", m.opcode, segs.join(", "));
}

/// The generated Elixir module for one protocol.
pub fn elixir(p: &Protocol) -> String {
    let module = format!("Redoubt.Wire.Proto.{}", camel(&p.name));
    let mut s = String::new();
    let _ = writeln!(s, "# Typed messages of the `{}` protocol.", p.name);
    let _ = writeln!(s, "#");
    let _ = writeln!(s, "# Generated by `redoubt-wire-gen` from the tables in `{}`.", p.source);
    let _ = writeln!(s, "# Do not edit: change the tables and run `cargo run -p redoubt-wire-gen`.");
    let _ = writeln!(s, "defmodule {module} do");
    let _ = writeln!(s, "  @moduledoc \"\"\"");
    let _ = writeln!(s, "  Codec for the `{}` protocol. A request or reply is `{{name, fields}}`, with `fields` a", p.name);
    let _ = writeln!(s, "  map holding exactly the table's non-handle fields; an error reply decodes to");
    let _ = writeln!(s, "  `{{:failed, error}}`; `:malformed` (code 1) is every protocol's error for a request that");
    let _ = writeln!(s, "  does not decode. Framing and errors: `Redoubt.Wire`.");
    let _ = writeln!(s, "  \"\"\"");
    s.push_str("  alias Redoubt.Wire, as: W\n\n");
    let shape = |m: &MessageDef| if m.inline() { ":inline" } else { ":buffer" };
    s.push_str("  # opcode => {name, shape, handles}; replies are keyed by their request's opcode.\n");
    let reqs: Vec<String> = p
        .messages
        .iter()
        .map(|m| format!("    {} => {{:{}, {}, {}}}", m.opcode, m.name, shape(m), handles(&m.fields).count()))
        .collect();
    let _ = writeln!(s, "  @requests %{{\n{}\n  }}", reqs.join(",\n"));
    let reps: Vec<String> = p
        .messages
        .iter()
        .map(|m| format!("    {} => {{:{}, {}, {}}}", m.opcode, m.name, shape(m), handles(&m.reply).count()))
        .collect();
    let _ = writeln!(s, "  @replies %{{\n{}\n  }}", reps.join(",\n"));
    let errs: Vec<String> = p.errors.iter().map(|e| format!("    {} => :{}", e.code, e.name)).collect();
    let _ = writeln!(s, "  @errors %{{\n{}\n  }}\n", errs.join(",\n"));

    s.push_str("  @doc \"\"\"\n  A message's layout: `{opcode, shape, fields, handles, reply}`, where `fields` lists\n");
    s.push_str("  `{name, type}` in order, `handles` lists the handles' names by slot, and `reply` is\n");
    s.push_str("  `{fields, handles}`.\n");
    // The kinds are documentation only (WIRE.md): checked by use, never on receipt.
    let kinds: Vec<String> = p
        .messages
        .iter()
        .flat_map(|m| {
            let req = handle_doc(&m.fields).map(|h| format!("  - `{}`: {h}", m.name));
            let rep = handle_doc(&m.reply).map(|h| format!("  - `{}` reply: {h}", m.name));
            req.into_iter().chain(rep)
        })
        .collect();
    if !kinds.is_empty() {
        s.push_str("\n  Handle kinds, from the table: documentation, checked by use (a handle of the wrong kind\n");
        s.push_str("  gets `WrongObject` on first use).\n\n");
        for k in kinds {
            let _ = writeln!(s, "{k}");
        }
    }
    s.push_str("  \"\"\"\n");
    for m in &p.messages {
        let reply = format!("{{{}}}", elixir_fields(&m.reply));
        let _ = writeln!(s, "  def layout(:{}), do: {{{}, {}, {}, {reply}}}", m.name, m.opcode, shape(m), elixir_fields(&m.fields));
    }
    s.push_str("  def layout(_), do: nil\n\n");

    s.push_str("  @doc \"Encodes a request: `{:ok, words, buffer}` or `{:error, reason}`.\"\n");
    s.push_str("  def encode(message), do: W.encode(message, @requests, &enc(:request, &1, &2))\n\n");
    s.push_str("  @doc \"Encodes a successful reply (status 0): `{:ok, words, buffer}` or `{:error, reason}`.\"\n");
    s.push_str("  def encode_reply(reply), do: W.encode_reply(reply, @replies, &enc(:reply, &1, &2))\n\n");
    s.push_str("  @doc \"The words of an error reply: `{:ok, words, <<>>}` or `{:error, :bad_message}`.\"\n");
    s.push_str("  def encode_error(error), do: W.encode_error(error, @errors)\n\n");
    s.push_str("  @doc \"Encodes a request for writing into a 9P file: `{:ok, bytes}` or `{:error, reason}`.\"\n");
    s.push_str("  def encode_file(message), do: W.encode_file(message, @requests, &enc(:request, &1, &2))\n\n");
    s.push_str("  @doc \"Decodes a request from its four words, its buffer and its handle count.\"\n");
    s.push_str("  def decode(words, buffer, handles), do: W.decode(words, buffer, handles, @requests, &read(:request, &1, &2))\n\n");
    s.push_str("  @doc \"Decodes the reply to the request with `opcode`: `{:ok, reply}`, `{:failed, error}` or `{:error, reason}`.\"\n");
    s.push_str("  def decode_reply(opcode, words, buffer, handles),\n");
    s.push_str("    do: W.decode_reply(opcode, words, buffer, handles, @replies, @errors, &read(:reply, &1, &2))\n\n");
    s.push_str("  @doc \"Decodes a request written into a 9P file.\"\n");
    s.push_str("  def decode_file(bytes), do: W.decode_file(bytes, @requests, &read(:request, &1, &2))\n\n");

    let (mut enc, mut read) = (String::new(), String::new());
    for m in &p.messages {
        elixir_clauses(&mut enc, &mut read, "request", m, &m.fields);
        elixir_clauses(&mut enc, &mut read, "reply", m, &m.reply);
    }
    s.push_str(&enc);
    s.push_str("  defp enc(_, _, _), do: throw({:wire, :bad_message})\n\n");
    s.push_str(&read);
    s.push_str("  defp read(_, _, _), do: {:error, :short_fields}\nend\n");
    s
}

/// The notes that may hold tables, relative to the repository root, sorted.
pub fn sources(root: &Path) -> Result<Vec<PathBuf>, String> {
    let mut found = Vec::new();
    for dir in ["docs", "libs/wire/tables"] {
        let entries = std::fs::read_dir(root.join(dir)).map_err(|e| format!("{dir}: {e}"))?;
        for entry in entries {
            let path = entry.map_err(|e| format!("{dir}: {e}"))?.path();
            if path.extension().is_some_and(|x| x == "md") {
                let rel = path.strip_prefix(root).map_err(|e| e.to_string())?;
                found.push(rel.to_path_buf());
            }
        }
    }
    found.sort();
    Ok(found)
}

/// Every generated file (path relative to the repository root, contents), from the notes.
pub fn generate(root: &Path) -> Result<Vec<(PathBuf, String)>, String> {
    let mut tables = Vec::new();
    for src in sources(root)? {
        let text = std::fs::read_to_string(root.join(&src)).map_err(|e| format!("{}: {e}", src.display()))?;
        let name = src.to_str().ok_or("non-UTF-8 path")?.replace('\\', "/");
        tables.push(parse(&name, &text)?);
    }
    let protocols = link(tables)?;
    let mut out = vec![(PathBuf::from("libs/wire/src/proto/mod.rs"), rust_mod(&protocols))];
    for p in &protocols {
        out.push((PathBuf::from(format!("libs/wire/src/proto/{}.rs", p.name)), rust(p)));
        out.push((PathBuf::from(format!("libs/wire/elixir/proto/{}.ex", p.name)), elixir(p)));
    }
    Ok(out)
}

/// Generated files that are missing or differ, and files in the output directories that
/// no table produces any more.
pub fn stale(root: &Path) -> Result<Vec<PathBuf>, String> {
    let expected = generate(root)?;
    let mut stale = Vec::new();
    for (path, contents) in &expected {
        if std::fs::read_to_string(root.join(path)).ok().as_deref() != Some(contents.as_str()) {
            stale.push(path.clone());
        }
    }
    stale.extend(orphans(root, &expected));
    Ok(stale)
}

/// Files in the output directories that no table generates.
pub fn orphans(root: &Path, expected: &[(PathBuf, String)]) -> Vec<PathBuf> {
    let mut found = Vec::new();
    for dir in ["libs/wire/src/proto", "libs/wire/elixir/proto"] {
        let Ok(entries) = std::fs::read_dir(root.join(dir)) else { continue };
        for entry in entries.flatten() {
            let rel = Path::new(dir).join(entry.file_name());
            if !expected.iter().any(|(p, _)| *p == rel) {
                found.push(rel);
            }
        }
    }
    found
}

