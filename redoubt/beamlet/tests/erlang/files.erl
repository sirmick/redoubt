%% Files through OTP's own file, file_server and file_io_server over prim_file.
-module(files).
-export([start/0]).
start() ->
    {ok, Cwd} = file:get_cwd(),
    D = filename:join(Cwd, "ftdir"),
    file:del_dir_r(D),
    ok = file:make_dir(D),
    F = filename:join(D, "a.txt"),
    ok = file:write_file(F, <<"hello\nworld\nthird line\n">>),
    {ok, Bin} = file:read_file(F),
    {ok, Fd} = file:open(F, [read]),
    L1 = io:get_line(Fd, ''),
    L2 = file:read_line(Fd),
    {ok, P} = file:position(Fd, cur),
    ok = file:close(Fd),
    {ok, Fd2} = file:open(F, [append]),
    ok = io:format(Fd2, "~p.~n", [{term, 42}]),
    ok = file:close(Fd2),
    {ok, Fd3} = file:open(F, [read, binary, raw, read_ahead]),
    {ok, Chunk} = file:read(Fd3, 5),
    {ok, Pr} = file:pread(Fd3, 6, 5),
    eof = file:pread(Fd3, 1000, 5),
    file:close(Fd3),
    ok = file:write_file(filename:join(D, "t.config"), "{a, 1}.\n{b, [x, y]}.\n"),
    {ok, Terms} = file:consult(filename:join(D, "t.config")),
    {ok, Info} = file:read_file_info(F),
    Size = element(2, Info), Type = element(3, Info),
    {ok, Names} = file:list_dir(D),
    ok = file:rename(F, filename:join(D, "b.txt")),
    E1 = file:read_file(F),
    E2 = file:make_dir(D),
    E3 = file:del_dir(D),
    ok = file:set_cwd(D),
    {ok, Cwd2} = file:get_cwd(),
    {ok, B2} = file:read_file("b.txt"),
    ok = file:set_cwd(Cwd),
    ok = file:delete(filename:join(D, "b.txt")),
    ok = file:delete(filename:join(D, "t.config")),
    ok = file:del_dir(D),
    Exists = filelib:is_dir(D),
    {Bin, L1, L2, P, Chunk, Pr, Terms, Size, Type, lists:sort(Names), E1, E2, E3,
     lists:suffix("ftdir", Cwd2), byte_size(B2), Exists}.
